#!/usr/bin/env node
/**
 * Public API contract emitter / checker (pack 01 doc 08 — contracts cannot
 * silently drift). Boots the real API, publishes a representative auction lot,
 * and records the FIELD SHAPE of every public response the frontend consumes
 * into `contracts/public-api.contract.json`.
 *
 *   node scripts/emit-contract.mjs           # regenerate the committed contract
 *   node scripts/emit-contract.mjs --check    # fail if the live API drifted from it
 *
 * The committed file is the shared source of truth: the backend `--check` mode
 * fails CI if a response changes without regenerating it, and the frontend
 * validates its DTOs against the same file — so neither side can drift silently.
 */
import { spawn } from 'node:child_process';
import { randomUUID } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { setTimeout as sleep } from 'node:timers/promises';
import PrismaPkg from '@prisma/client';

const { PrismaClient } = PrismaPkg;

const BASE = 'http://localhost:4000';
const V1 = `${BASE}/api/v1`;
const OUT = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'contracts',
  'public-api.contract.json',
);
const CHECK = process.argv.includes('--check');

/** Recursively describe a value's shape: object → sorted {field: kind}. */
function shape(v) {
  if (Array.isArray(v)) return v.length ? [shape(v[0])] : ['unknown'];
  if (v === null) return 'null';
  if (typeof v === 'object') {
    const out = {};
    for (const k of Object.keys(v).sort()) out[k] = shape(v[k]);
    return out;
  }
  return typeof v;
}

async function call(url, { token, method = 'GET', body } = {}) {
  const res = await fetch(url, {
    method,
    headers: {
      'content-type': 'application/json',
      ...(token ? { authorization: `Bearer ${token}` } : {}),
    },
    body: body ? JSON.stringify(body) : undefined,
  });
  let json = null;
  try {
    json = await res.json();
  } catch {
    /* no body */
  }
  return { status: res.status, json };
}
const v1 = (p, o) => call(`${V1}${p}`, o);
const v2 = (p, o) => call(`${BASE}/api/v2${p}`, o);

async function waitForHealth() {
  for (let i = 0; i < 60; i += 1) {
    try {
      if ((await fetch(`${BASE}/healthz`)).ok) return true;
    } catch {
      /* not up */
    }
    await sleep(500);
  }
  return false;
}

async function main() {
  const child = spawn('node', ['apps/api/dist/main.js'], {
    stdio: ['ignore', 'pipe', 'pipe'],
    env: process.env,
  });
  const logs = [];
  child.stdout.on('data', (d) => logs.push(d.toString()));
  child.stderr.on('data', (d) => logs.push(d.toString()));
  const prisma = new PrismaClient();

  try {
    if (!(await waitForHealth())) {
      console.error('API did not start:\n' + logs.join(''));
      process.exit(1);
    }

    // Buyer customer (for the authenticated dashboard token).
    const buyerId = (
      await v1('/customers', {
        method: 'POST',
        body: { legalName: 'Buyer', email: `b${Date.now()}@ex.com` },
      })
    ).json.id;
    const buyerToken = (
      await v1('/dev/token', { method: 'POST', body: { roles: ['customer'], customerId: buyerId } })
    ).json.token;

    // Seed a representative published auction lot directly (deterministic shape).
    const assetId = randomUUID();
    const id = randomUUID();
    const auctionId = randomUUID();
    await prisma.asset.create({
      data: {
        id: assetId,
        category: 'vehicles',
        subcategory: 'suv_4x4',
        attributes: { make: 'Toyota' },
      },
    });
    await prisma.listing.create({
      data: {
        id,
        assetId,
        saleMethod: 'TIMED_AUCTION',
        status: 'scheduled',
        publicRef: `CONTRACT-${Date.now()}`,
        title: 'Contract Lot',
      },
    });
    await prisma.auction.create({
      data: {
        id: auctionId,
        listingId: id,
        status: 'scheduled',
        currency: 'LKR',
        startsAt: new Date(Date.now() - 1000),
        endsAt: new Date(Date.now() + 3_600_000),
        openingBidMinor: 1_000_000n,
        incrementMinor: 25_000n,
      },
    });

    const contract = {
      version: 1,
      note: 'Generated by scripts/emit-contract.mjs from live API responses. Shared with the frontend to prevent silent DTO drift (pack 01 doc 08).',
      endpoints: {
        'GET /api/v2/catalogue': shape((await v2('/catalogue?limit=1')).json),
        'GET /api/v2/catalogue/row': shape(
          (await v2('/catalogue/row?category=vehicles&limit=1')).json,
        ),
        'GET /api/v2/catalogue/:id': shape((await v2(`/catalogue/${id}`)).json),
        'GET /auctions/:id/state': shape((await v1(`/auctions/${auctionId}/state`)).json),
        'GET /api/v2/me/dashboard': shape((await v2('/me/dashboard', { token: buyerToken })).json),
      },
    };

    const generated = JSON.stringify(contract, null, 2) + '\n';
    if (CHECK) {
      // Compare parsed content, not raw bytes, so whitespace/formatting (e.g.
      // prettier normalising the committed file) is not mistaken for API drift.
      const canon = (s) => JSON.stringify(JSON.parse(s));
      const committed = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
      if (!committed || canon(committed) !== canon(generated)) {
        console.error(
          '✗ Public API contract drift: live responses differ from contracts/public-api.contract.json.',
        );
        console.error(
          '  Run `node scripts/emit-contract.mjs` to regenerate, then sync it to the frontend.',
        );
        process.exit(1);
      }
      console.log('✓ Public API contract matches the live API.');
    } else {
      writeFileSync(OUT, generated);
      console.log(`Wrote ${OUT}`);
    }
  } finally {
    await prisma.$disconnect().catch(() => {});
    child.kill('SIGTERM');
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
